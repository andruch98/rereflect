"""Resolve one unambiguous source-only follow-up without another model request.

Everything outside the narrowly recognized exchange falls back to the normal
conversation path. In particular, this is not a general intent classifier.
"""
from __future__ import annotations

import json
import re

from src.services import ask_genius as service


def _question_text(value: str) -> str:
    return re.sub(r'\s+', ' ', value.strip()).casefold().rstrip('?.! ')


def _source_only_question(question: str) -> bool:
    text = _question_text(question)
    return bool(re.fullmatch(
        r'(?:please )?(?:show(?: me)?|let me see|give me|list|display|open) '
        r'(?:(?:the )?(?:each|all|those|these|supporting) reviews?'
        r'|(?:the )?reviews? for each(?: topic)?)'
        r'(?: please)?', text))


def _broad_negative_question(question: str) -> bool:
    text = _question_text(question)
    period = r'(?: (?:during|for) (?:this|the selected) period)?'
    return bool(re.fullmatch(
        r'(?:what are|which are) (?:the )?(?:bad|negative) topics'
        r'(?: in (?:the )?reviews)?' + period, text)
        or re.fullmatch(
            r'which topics had negative feedback(?: in reviews)?' + period,
            text))


def _frequent_topics_question(question: str) -> bool:
    return _question_text(question) == (
        'which topics came up most often in reviews during this period')


def _topic_bullets(answer: str, known_topics: set[str]) -> list[str] | None:
    """Require a complete, flat list of exact topic labels with descriptions.

    Only negative qualifiers are harmless here: a qualifier such as ``late fees``
    could describe a narrower theme whose evidence needs the normal model path.
    """
    topics = []
    intro_seen = False
    for line in answer.splitlines():
        if not line.strip():
            continue
        if not re.match(r'^[-*•] ', line):
            # A short lead-in ending in a colon may precede the list. Reject
            # continuations, nested lists, extra conclusions and evidence offers.
            if (topics or intro_seen or not line.endswith(':')
                    or line.startswith((' ', '\t', '-', '*', '•'))):
                return None
            intro_seen = True
            continue
        heading, separator, body = line[2:].partition(':')
        if not separator:
            return None
        if heading.startswith('**'):
            heading = heading[2:]
            if heading.endswith('**'):
                heading = heading[:-2]
            elif body.startswith('**'):
                body = body[2:]
            elif re.fullmatch(r'[^*]+\*\* \([^()]*\)', heading):
                # Supports **Topic** (negative aspects): ... as well.
                heading = heading.replace('**', '', 1)
            else:
                return None
        if '**' in heading or not body.strip():
            return None
        match = re.fullmatch(
            r'(.+?)(?: \((?:negative|negative aspects|negative feedback|complaints)\))?',
            heading.strip())
        topic = match.group(1) if match else None
        if topic not in known_topics or topic in topics:
            return None
        topics.append(topic)
    return topics or None


def topic_review_followup(
    question: str, evidence: dict, history: list[dict],
) -> tuple[str, list[dict]] | None:
    """Attach verified negative-topic sources to the immediately prior answer.

    Accept an initial broad-negative-topic exchange, or the approved preceding
    frequent-topics exchange. Other history might carry a narrower source/rating/
    theme scope, so it is intentionally left for the existing conversation path.
    No additional prose, counts, IDs or links are generated by this helper.
    """
    if not _source_only_question(question) or len(history) not in (2, 4):
        return None
    if [message.get('role') for message in history] != ['user', 'assistant'] * (len(history) // 2):
        return None
    if not all(isinstance(message.get('content'), str) for message in history):
        return None
    if len(history) == 4 and not _frequent_topics_question(history[0]['content']):
        return None
    if not _broad_negative_question(history[-2]['content']):
        return None
    answer = history[-1]['content'].strip()
    if not answer or len(answer) > service.DEFAULT_ANSWER_CHARS:
        return None
    # Selector validation does not verify previously written counts. Leave
    # numeric claims for a fresh answer grounded in the current evidence.
    if re.search(r'\d|\b(?:zero|one|two|three|four|five|six|seven|eight|nine|ten|'
                 r'eleven|twelve|dozen|hundred|thousand|percent|percentage|half|majority)\b',
                 answer, re.I):
        return None
    known_topics = {
        topic['name'] for record in evidence.get('reviews', [])
        for topic in record.get('saved_analysis', {}).get('topics', [])
    }
    topics = _topic_bullets(answer, known_topics)
    if not topics:
        return None
    try:
        validated_answer, sources = service.validate_answer(json.dumps({
            'answer': answer,
            'selections': [{'topic': topic, 'sentiment': 'negative'} for topic in topics],
        }), evidence, expanded=True)
    except (ValueError, KeyError, TypeError):
        return None
    # Fail closed if a topic's earlier claim cannot be supported by the current
    # authorized records. Keep selection/source order, including topic overlap.
    if {source.get('topic') for source in sources} != set(topics):
        return None
    return validated_answer, sources
